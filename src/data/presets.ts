export interface PaletteItem extends Omit<SoundBubble, 'id' | 'regions'> {
  diagramName?: string;
}

export const getDiagramName = (name: string): string => {
  if (!name) return '';
  const trimmed = name.trim();
  const lower = trimmed.toLowerCase();

  // Drums: Kick, Snare, Tom show as just "Kick", "Snare", "Tom" on the diagram
  if (lower === 'kick drum' || lower === 'kick') {
    return 'Kick';
  }
  if (lower === 'snare drum' || lower === 'snare') {
    return 'Snare';
  }
  if (lower === 'tom drum' || lower === 'tom' || lower === 'toms' || lower === 'tom drums') {
    return 'Tom';
  }

  // Guitars
  switch (trimmed) {
    case 'Electric Guitar (Rhythm)':
      return 'E Guit (Rhythm)';
    case 'Electric Guitar (Lead)':
      return 'E Guit (Lead)';
    case 'Acoustic Guitar (Rhythm)':
      return 'A Guit (Rhythm)';
    case 'Acoustic Guitar (Lead)':
      return 'A Guit (Lead)';
    case 'Piano (Grand/Upright)':
    case 'Piano':
      return 'Piano';
    case 'Electric Piano':
      return 'E Piano';
    case 'Synth (Generic)':
      return 'Synth';
    case 'Brass/Horn Section':
    case 'Brass / Horn Section':
      return 'Horn Section';
    default:
      if (lower === 'piano (grand/upright)') return 'Piano';
      return trimmed;
  }
};

